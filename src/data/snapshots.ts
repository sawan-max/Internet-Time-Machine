export function getSnapshots(domain: string): Snapshot[] {
  return snapshotData[domain] || [];
}

export function getSnapshot(domain: string, year: number): Snapshot | undefined {
  const snapshots = snapshotData[domain] || [];
  return snapshots.find(s => s.year === year) || snapshots.reduce((closest, s) =>
    Math.abs(s.year - year) < Math.abs(closest.year - year) ? s : closest, snapshots[0]);
}

export function getAvailableYears(domain: string): number[] {
  return (snapshotData[domain] || []).map(s => s.year);
}
